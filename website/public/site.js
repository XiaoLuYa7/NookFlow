function activeLanguage() {
  return document.documentElement.lang.startsWith("zh") ? "zh" : "en";
}

function updateThemeLabel() {
  const copy = translations[activeLanguage()];
  const key = document.documentElement.dataset.theme === "dark" ? "themeToLight" : "themeToDark";
  themeToggle.title = copy[key];
  themeToggle.setAttribute("aria-label", copy[key]);
}

function applyTheme(theme, persist = true) {
  document.documentElement.dataset.theme = theme;
  themeMeta?.setAttribute("content", theme === "dark" ? "#000000" : "#f5f5f7");
  if (persist) localStorage.setItem("nookflow-theme", theme);
  updateThemeLabel();
}

function applyLanguage(language) {
  const copy = translations[language];
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.title = copy.title;
  document.querySelector('meta[name="description"]')?.setAttribute("content", copy.description);
  document.querySelectorAll("[data-i18n]").forEach(element => {
    const value = copy[element.dataset.i18n];
    if (value) element.textContent = value;
  });
  document.querySelectorAll("[data-i18n-aria]").forEach(element => {
    const value = copy[element.dataset.i18nAria];
    if (value) element.setAttribute("aria-label", value);
  });
  document.querySelectorAll("[data-i18n-title]").forEach(element => {
    const value = copy[element.dataset.i18nTitle];
    if (value) {
      element.title = value;
      element.setAttribute("aria-label", value);
    }
  });
  document.querySelectorAll("[data-i18n-alt]").forEach(element => {
    const value = copy[element.dataset.i18nAlt];
    if (value) element.alt = value;
  });
  languageToggle.textContent = language === "zh" ? "EN" : "中";
  localStorage.setItem("nookflow-language", language);
  updateThemeLabel();
  renderProductPrice();
}

function currency(amountCents) {
  const locale = activeLanguage() === "zh" ? "zh-CN" : "en-US";
  return new Intl.NumberFormat(locale, { style: "currency", currency: "CNY" }).format(amountCents / 100);
}

function renderProductPrice() {
  if (!productInfo) return;
  const copy = translations[activeLanguage()];
  if (!productInfo.paymentEnabled) {
    licensePrice.textContent = copy.paymentUnavailable;
    openCheckout.disabled = true;
    checkoutSubmit.disabled = true;
    checkoutSubmit.querySelector("span").textContent = copy.paymentUnavailable;
    return;
  }
  const value = currency(productInfo.amountCents);
  licensePrice.textContent = value;
  checkoutAmount.textContent = value;
  const pricingAmount = document.querySelector("#pricingAmount");
  if (pricingAmount) pricingAmount.textContent = (productInfo.amountCents / 100).toFixed(2);
  openCheckout.disabled = false;
  checkoutSubmit.disabled = false;
  checkoutSubmit.querySelector("span").textContent = copy.continuePayment;
}

async function loadProduct() {
  checkoutSubmit.disabled = true;
  checkoutSubmit.querySelector("span").textContent = translations[activeLanguage()].paymentLoading;
  try {
    const response = await fetch("/api/store/product", { headers: { Accept: "application/json" } });
    if (!response.ok) throw new Error("product_unavailable");
    productInfo = await response.json();
    renderProductPrice();
  } catch (_) {
    const copy = translations[activeLanguage()];
    licensePrice.textContent = copy.paymentUnavailable;
    openCheckout.disabled = true;
    checkoutSubmit.disabled = true;
    checkoutSubmit.querySelector("span").textContent = copy.paymentUnavailable;
  }
}

function readCheckout() {
  try {
    const saved = JSON.parse(localStorage.getItem(checkoutStorageKey));
    const expired = saved?.expiresAt ? Date.now() > saved.expiresAt : Date.now() - saved?.savedAt > 86_400_000;
    if (!saved?.orderNo || !saved?.token || expired) {
      localStorage.removeItem(checkoutStorageKey);
      return null;
    }
    return saved;
  } catch (_) {
    localStorage.removeItem(checkoutStorageKey);
    return null;
  }
}

function openCheckoutDialog(showResult = false) {
  checkoutTrigger = document.activeElement;
  checkoutBackdrop.hidden = false;
  document.body.classList.add("checkout-open");
  checkoutForm.hidden = showResult;
  checkoutResult.hidden = !showResult;
  checkoutError.hidden = true;
  requestAnimationFrame(() => checkoutBackdrop.classList.add("is-visible"));
  (showResult ? document.querySelector("#checkPaymentNow") : document.querySelector("#checkoutEmail"))?.focus();
}

function closeCheckoutDialog() {
  checkoutBackdrop.classList.remove("is-visible");
  document.body.classList.remove("checkout-open");
  clearTimeout(paymentPollTask);
  paymentPollTask = null;
  setTimeout(() => {
    checkoutBackdrop.hidden = true;
    checkoutTrigger?.focus?.();
  }, reducedMotion.matches ? 0 : 180);
}

function showPaymentResult(code) {
  const copy = translations[activeLanguage()];
  checkoutForm.hidden = true;
  checkoutResult.hidden = false;
  document.querySelector("#checkoutSpinner").hidden = Boolean(code);
  document.querySelector("#checkoutResultTitle").textContent = code ? copy.paymentSucceeded : copy.waitingPayment;
  document.querySelector("#checkoutResultBody").textContent = code ? copy.paymentSucceededBody : copy.waitingPaymentBody;
  document.querySelector("#activationResult").hidden = !code;
  document.querySelector("#checkPaymentNow").hidden = Boolean(code);
  if (code) document.querySelector("#purchasedActivationCode").textContent = code;
}

async function requestOrderStatus(forceRefresh = false) {
  const checkout = readCheckout();
  if (!checkout) return null;
  const endpoint = `/api/store/orders/${encodeURIComponent(checkout.orderNo)}${forceRefresh ? "/refresh" : ""}`;
  const response = await fetch(endpoint, {
    method: forceRefresh ? "POST" : "GET",
    headers: { Accept: "application/json", "X-Checkout-Token": checkout.token }
  });
  if (!response.ok) throw new Error("order_unavailable");
  return response.json();
}

async function pollPayment(forceRefresh = false) {
  clearTimeout(paymentPollTask);
  try {
    const order = await requestOrderStatus(forceRefresh);
    if (!order) return;
    if (order.status === "LICENSE_ISSUED" && order.activationCode) {
      showPaymentResult(order.activationCode);
      return;
    }
    if (["FAILED", "REFUNDED", "CLOSED"].includes(order.status)) {
      localStorage.removeItem(checkoutStorageKey);
      const copy = translations[activeLanguage()];
      document.querySelector("#checkoutSpinner").hidden = true;
      document.querySelector("#checkoutResultTitle").textContent = copy.paymentFailed;
      document.querySelector("#checkoutResultBody").textContent = copy.paymentFailedBody;
      return;
    }
  } catch (_) {
    // A temporary network error should not encourage a second payment.
  }
  paymentPollCount += 1;
  if (!checkoutBackdrop.hidden && paymentPollCount < 60) {
    paymentPollTask = setTimeout(() => pollPayment(paymentPollCount % 5 === 0), 2000);
  }
}

async function startCheckout(event) {
  event.preventDefault();
  if (!productInfo?.paymentEnabled) return;
  checkoutError.hidden = true;
  checkoutSubmit.disabled = true;
  checkoutSubmit.querySelector("span").textContent = translations[activeLanguage()].paymentLoading;
  const data = new FormData(checkoutForm);
  try {
    const response = await fetch("/api/store/orders", {
      method: "POST",
      headers: { "Content-Type": "application/json", Accept: "application/json" },
      body: JSON.stringify({ email: data.get("email"), channel: data.get("channel") })
    });
    if (!response.ok) throw new Error("checkout_failed");
    const checkout = await response.json();
    localStorage.setItem(checkoutStorageKey, JSON.stringify({
      orderNo: checkout.orderNo,
      token: checkout.checkoutToken,
      expiresAt: checkout.expiresAt,
      savedAt: Date.now()
    }));
    window.location.assign(checkout.redirectUrl);
  } catch (_) {
    checkoutError.textContent = activeLanguage() === "zh" ? "暂时无法创建订单，请稍后重试。" : "The order could not be created. Try again shortly.";
    checkoutError.hidden = false;
    checkoutSubmit.disabled = false;
    checkoutSubmit.querySelector("span").textContent = translations[activeLanguage()].continuePayment;
  }
}

function restoreCheckoutAfterNavigation() {
  clearTimeout(paymentPollTask);
  paymentPollTask = null;
  checkoutSubmit.querySelector("span").textContent = translations[activeLanguage()].continuePayment;
  checkoutSubmit.disabled = !productInfo?.paymentEnabled;
}

function resumeCheckout() {
  const checkout = readCheckout();
  if (!checkout) {
    openCheckoutDialog(false);
    return;
  }
  paymentPollCount = 0;
  openCheckoutDialog(true);
  showPaymentResult(null);
  pollPayment(true);
}

async function copyPurchasedCode() {
  const code = document.querySelector("#purchasedActivationCode").textContent.trim();
  if (!code) return;
  try {
    await navigator.clipboard.writeText(code);
    const copy = translations[activeLanguage()];
    copyActivationCode.textContent = copy.copiedCode;
    setTimeout(() => { copyActivationCode.textContent = copy.copyCode; }, 1600);
  } catch (_) {
    window.getSelection()?.selectAllChildren(document.querySelector("#purchasedActivationCode"));
  }
}

function updateDemoPlayback() {
  if (document.hidden || reducedMotion.matches) {
    heroDemo?.pause();
    dragDemo?.pause();
  } else {
    heroDemo?.play().catch(() => {});
    if (dragDemo?.classList.contains("is-active")) {
      dragDemo.play().catch(() => {});
    } else {
      dragDemo?.pause();
    }
  }
}

